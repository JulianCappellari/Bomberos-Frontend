import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.BOMBEROS_PLAYWRIGHT_PATH || "playwright");
if (!process.env.BOMBEROS_TEST_PASSWORD) throw Error("Use solo el preview temporal de test:members");
const output = fileURLToPath(new URL("../../tmp/ui/", import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true }), errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on("pageerror", error => errors.push(error.message));
  page.on("dialog", dialog => dialog.accept());
  await page.goto("http://localhost:3217/login");
  await page.getByPlaceholder("Tu nombre de usuario").fill("member_test_0");
  await page.locator('input[type="password"]').fill(process.env.BOMBEROS_TEST_PASSWORD);
  await page.getByRole("button", { name: "Ingresar al Cuartel" }).click();
  await page.waitForURL(/\/(dashboard|admin)$/);
  await page.goto("http://localhost:3217/admin");
  const areas = page.getByRole("navigation", { name: "Areas de administracion" });
  await page.getByRole("heading", { name: "Estado de las cuentas" }).waitFor();
  assert.equal(await page.getByRole("heading", { name: "Ultimas alertas operativas" }).count(), 0);
  await page.screenshot({ path: output + "admin-ordenado-resumen-pc.png", fullPage: true });
  await areas.getByRole("button", { name: "Personal", exact: true }).click();
  await page.getByRole("searchbox", { name: "Buscar personal" }).fill("member_test_2");
  await page.getByRole("region", { name: "Listado de personal" }).getByRole("button", { name: /member_test_2/ }).click();
  await page.getByLabel("Nombre completo", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("Accion sobre la cuenta").count(), 0);
  const profile = page.getByRole("navigation", { name: "Secciones de la ficha" });
  await profile.getByRole("button", { name: "Cargo y permisos" }).click();
  await page.getByRole("combobox", { name: /Estado de cuenta/ }).selectOption("no");
  await page.getByRole("button", { name: "Guardar cargo y estado" }).click();
  await page.getByRole("status").filter({ hasText: "Cargo y estado actualizados" }).waitFor();
  await page.getByRole("combobox", { name: /Estado de cuenta/ }).selectOption("yes");
  await page.getByRole("button", { name: "Guardar cargo y estado" }).click();
  await page.getByRole("status").filter({ hasText: "Cargo y estado actualizados" }).waitFor();
  await profile.getByRole("button", { name: "Seguridad", exact: true }).click();
  await page.getByLabel("Accion sobre la cuenta").waitFor();
  assert.equal(await page.getByLabel("Nombre completo", { exact: true }).count(), 0);
  await page.reload();
  await page.getByLabel("Accion sobre la cuenta").waitFor();
  await page.getByRole("navigation", { name: "Secciones de la ficha" }).getByRole("button", { name: "Prendas", exact: true }).click();
  await page.getByRole("heading", { name: "Prendas personales declaradas" }).waitFor();
  await page.goBack();
  await page.getByLabel("Accion sobre la cuenta").waitFor();
  for (const width of [1440, 360, 320]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: output + `admin-ordenado-seguridad-${width}.png`, fullPage: true });
  }
  await areas.getByRole("button", { name: "Gestion del cuartel" }).click();
  await page.getByRole("searchbox", { name: "Buscar modulo de gestion" }).fill("Combustible");
  await page.getByRole("link", { name: "Combustible", exact: true }).waitFor();
  assert.equal(await page.getByRole("link", { name: "Mantenimiento", exact: true }).count(), 0);
  await page.getByRole("searchbox", { name: "Buscar modulo de gestion" }).fill("");
  await page.screenshot({ path: output + "admin-ordenado-modulos-320.png", fullPage: true });
  await page.getByRole("button", { name: "Nueva cuenta", exact: true }).click();
  const run = Date.now().toString();
  await page.getByLabel("Usuario", { exact: true }).fill(`admin_ui_${run}`);
  await page.getByLabel("Nombre completo", { exact: true }).fill("Cuenta temporal de interfaz");
  await page.getByLabel("DNI", { exact: true }).fill(run);
  await page.getByLabel("Legajo", { exact: true }).fill(`UI-${run}`);
  await page.getByLabel("Clave inicial (minimo 12 caracteres)").fill(process.env.BOMBEROS_TEST_PASSWORD);
  await page.getByRole("button", { name: "Crear cuenta", exact: true }).click();
  await page.getByRole("heading", { name: "Cuenta temporal de interfaz", exact: true }).waitFor();
  await page.getByLabel("Nombre completo", { exact: true }).fill("Cuenta temporal actualizada");
  await page.getByRole("button", { name: "Guardar datos personales" }).click();
  await page.getByRole("status").filter({ hasText: "Datos personales actualizados" }).waitFor();
  await page.getByRole("navigation", { name: "Secciones de la ficha" }).getByRole("button", { name: "Seguridad", exact: true }).click();
  await page.getByLabel("Accion sobre la cuenta").selectOption("archive");
  await page.getByLabel("Motivo administrativo", { exact: true }).fill("Baja de cuenta temporal creada en la prueba de interfaz");
  await page.getByRole("button", { name: "Confirmar accion administrativa" }).click();
  await page.getByText("Esta cuenta ya no esta disponible. Selecciona otra.").waitFor();
  assert.deepEqual(errors, []);
  console.log("Panel admin UI: filtros, alta/edicion/baja, pausa/reactivacion, datos/seguridad, recarga y Atras; PC/360/320px sin desbordes ni errores JS.");
} catch (error) {
  await browser.contexts()[0]?.pages()[0]?.screenshot({ path: output + "admin-fallo.png", fullPage: true });
  throw error;
} finally { await browser.close(); }
